#!/usr/bin/env node
// Extracts the Mozilla CA bundle txiki.js ALREADY vendors and ALREADY trusts
// for real TLS (mbedtls's TLSTcp socket class, and every libwebsockets
// https:// fetch()/wss:// connection — see mod_tls.c/lws-utils.c) into a
// plain-PEM sibling asset the node-shim's tls.cjs can read at runtime, fused
// or not (libexec/quaude-fuse.js sweeps every file under node-shim/modules/
// verbatim, no extension filter).
//
// WHY extract rather than add a new engine primitive: tls.rootCertificates
// was stubbed empty with the header comment "no bundled Mozilla CA store
// reachable from JS" — true only in the narrow sense that nothing exposed it
// to JS; the engine's cacert.c already carries the exact bundle, dated and
// regenerated by txiki.js's own scripts/update-ca-bundle.sh (sourced from
// https://curl.se/ca/cacert.pem, itself Mozilla's certdata.txt). Exposing it
// via a new C primitive would mean patching mod_tls.c and rebuilding/
// re-verifying every tjs leg in the build matrix — real engine-change scope.
// Extracting the SAME already-vendored, already-trusted text at dev/build
// time is a JS/build-only change with identical provenance: the certs this
// script emits are byte-for-byte what mbedtls/libwebsockets already verify
// real HTTPS against in this engine today, not a separately-sourced or
// invented set.
//
// STALENESS: re-run this script whenever cacert.c is refreshed by
// update-ca-bundle.sh (spike/quickjs/vendor/txiki.js/scripts/) — there is no
// automatic link between the two files; test/tls-cacert-pem.test.cjs checks
// the shipped .pem stays in sync with cacert.c's CURRENT content so a stale
// extraction is a loud test failure, not a silent drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CACERT_C = path.join(REPO, 'spike/quickjs/vendor/txiki.js/src/cacert.c');
const OUT_PEM = path.join(REPO, 'libexec/node-shim/modules/tls-cacert.pem');

// Decode the C source's `const char tjs_cacert_pem[] = "line1\n" "line2\n" ...;`
// into the plain text it represents. The generator (update-ca-bundle.sh) only
// ever emits whole-line string literals ending in a literal `\n` escape — no
// other C escapes appear in a curl cacert.pem extract (verified: grepped for
// any `\X` escape besides `\n` across the current file — none found). Decode
// defensively anyway (`\\`, `\"`, `\n`) rather than assume, so a genuinely
// different escape in a future regeneration fails LOUD (an unrecognized
// backslash sequence is left as-is, which downstream PEM/cert-count
// validation in the test will catch as corrupted output).
export function extractPemFromCacertC(src) {
  const m = /tjs_cacert_pem\[\]\s*=\s*((?:\s*"(?:[^"\\]|\\.)*"\s*)+);/.exec(src);
  if (!m) throw new Error('extractPemFromCacertC: tjs_cacert_pem[] literal not found — cacert.c format changed?');
  const literalBlock = m[1];
  const strRe = /"((?:[^"\\]|\\.)*)"/g;
  let out = '';
  let sm;
  while ((sm = strRe.exec(literalBlock))) {
    out += sm[1].replace(/\\(.)/g, (_, c) => (c === 'n' ? '\n' : c === 't' ? '\t' : c));
  }
  return out;
}

export function main() {
  const src = fs.readFileSync(CACERT_C, 'utf8');
  const pem = extractPemFromCacertC(src);
  const certCount = (pem.match(/-----BEGIN CERTIFICATE-----/g) || []).length;
  if (certCount < 50) throw new Error(`extract-cacert-pem: only found ${certCount} certificates — suspiciously low, refusing to write`);
  fs.writeFileSync(OUT_PEM, pem);
  console.log(`extract-cacert-pem: wrote ${OUT_PEM} (${pem.length} bytes, ${certCount} certificates)`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
