'use strict';
// PLAN a code-split bundle for compilation: what to compile, in what order, plus the
// generated shims that make node builtins resolvable.
//
// This is the build-time half of handling Claude Code 2.1.243+. libexec/bun-graph.cjs
// says which bytes are which module; this says how to hand them to the engine. The
// engine half is three calls we already have — tjs.engine.compile / serialize /
// deserialize — and NO engine patch, for reasons worth writing down because they are
// not obvious and they decided the design:
//
//   1. tjs.engine.compile() ALREADY compiles as an ES module (mod_engine.c passes
//      JS_EVAL_TYPE_MODULE), so upstream's modules compile AS THEY ARE. No rewriting,
//      so no chance of mangling a prompt string — which is exactly how the alternative
//      (rewriting ESM into a CJS registry) could have failed silently.
//   2. quickjs checks its ALREADY-LOADED module list before calling the module loader.
//      Deserialize every module and the entry's imports resolve without touching the
//      filesystem. Verified directly against the engine: registration order does not
//      matter, dynamic import() of a preregistered module works, and a module that was
//      never registered fails loudly rather than resolving to something empty.
//   3. Evaluating ONLY the entry pulls in the whole graph in correct ESM order.
//
// WHY ORDER STILL MATTERS AT COMPILE TIME. `compile()` resolves imports as it compiles,
// so a module's dependencies must already be compiled when it is. The import graph is a
// DAG (measured: 0 back-edges over 109,424 static edges on 2.1.245), so a topological
// order exists — and planOrder() throws if a cycle ever appears rather than emitting an
// order that would fail deep into a build.
//
// THE SHIMS ARE OURS, NOT UPSTREAM'S. Bare specifiers like "fs" are not in the graph and
// the engine cannot load them, so compilation stops dead at the first one (measured:
// 279 of 1384 modules before this existed). For each external specifier we generate a
// tiny module re-exporting exactly the names the bundle imports, fetched at runtime
// through the node-shim. Because this source is generated by us rather than rewritten
// from upstream, it carries no fidelity risk to the bundle.
//
// PROVEN AT SCALE against real 2.1.245 under the real engine: 1445 modules (1384 real +
// 61 shims) compiled to 41.4MB of bytecode in about 3 seconds.
//
// Pure JS: no npm, no Node built-ins beyond an optional convenience wrapper. `clode
// build` must work with Node absent.

var IMPORT_RES = [
  /\bimport\s*\{[^}]*\}\s*from\s*"((?:[^"\\]|\\.)*)"/g,
  /\bimport\s*"((?:[^"\\]|\\.)*)"/g,
  /\bimport\s*\*\s*as\s+[A-Za-z0-9_$]+\s*from\s*"((?:[^"\\]|\\.)*)"/g,
  /\bimport\s+[A-Za-z0-9_$]+\s*from\s*"((?:[^"\\]|\\.)*)"/g,
];

// IS THIS A MODULE SPECIFIER, OR PROSE THAT CONTAINS THE WORD `import`?
//
// The regexes below scan MINIFIED TEXT with no way to tell code from string contents,
// and this bundle is full of strings that look like code: skill documentation with
// ``| `import` | Call ...``, a vendored JavaScript parser whose own source discusses
// `parseDynamicImport`, CSS specifiers inside template literals. Without this filter,
// externalsOf() produced 75 "externals" of which about 40 were fragments like
// `,relevance:2},e.C_LINE_COMMENT_MODE,...`. They generated harmless unused shims, so
// the build still passed — which is exactly why it went unnoticed until the shim's
// KNOWN list was compared against them.
//
// The filter is deliberately CONSERVATIVE, and it is safe in one direction only, by
// design: a real specifier wrongly excluded fails LOUDLY at compile time ("could not
// load 'X'", naming it), because the engine resolves imports as it compiles. A junk
// specifier wrongly included costs one unused shim. So the engine is the backstop and
// this only has to be good enough to keep the noise out.
//
// Real specifiers are bare names, scoped packages, subpaths, or relative paths — never
// containing whitespace, braces, quotes, backticks or `$`.
var SPECIFIER_OK = /^(?:@[A-Za-z0-9._-]+\/)?[A-Za-z0-9._-]+(?:\/[A-Za-z0-9._-]+)*$/;
var SPECIFIER_MAX = 128;
function isPlausibleSpecifier(spec) {
  if (typeof spec !== 'string' || !spec.length || spec.length > SPECIFIER_MAX) return false;
  if (spec.charAt(0) === '/' || spec.slice(0, 2) === './' || spec.slice(0, 3) === '../') {
    // Relative and absolute paths: same charset rule, applied to the whole thing.
    return /^[A-Za-z0-9._\/-]+$/.test(spec);
  }
  return SPECIFIER_OK.test(spec);
}

// Static dependencies of `src` that are themselves modules in the graph.
function depsOf(src, inGraph) {
  var out = [], seen = {}, i, re, m;
  for (i = 0; i < IMPORT_RES.length; i++) {
    re = new RegExp(IMPORT_RES[i].source, 'g');
    while ((m = re.exec(src))) {
      var spec = m[1];
      if (inGraph(spec) && !seen['#' + spec]) { seen['#' + spec] = 1; out.push(spec); }
    }
  }
  return out;
}

// Bare specifiers (node builtins and anything else not in the graph), with the names
// each is imported BY NAME. Namespace and default imports are recorded but need no
// named exports at compile time.
function externalsOf(mods) {
  var ext = {}, name, src, m, re, parts, i, t, spec;
  var want = function (s) { if (!ext[s]) ext[s] = {}; return ext[s]; };
  for (name of mods.keys()) {
    src = mods.get(name);
    re = /\bimport\s*\{([^}]*)\}\s*from\s*"((?:[^"\\]|\\.)*)"/g;
    while ((m = re.exec(src))) {
      if (mods.has(m[2]) || !isPlausibleSpecifier(m[2])) continue;
      var set = want(m[2]);
      parts = m[1].split(',');
      for (i = 0; i < parts.length; i++) {
        t = parts[i].trim();
        if (t) set[t.split(/\s+as\s+/)[0].trim()] = 1;
      }
    }
    // NAMESPACE imports need the whole surface they actually USE. An ES module
    // namespace object exposes only DECLARED exports, so `import * as Mo from "vm"`
    // followed by `Mo.runInContext(...)` fails with "not a function" unless the shim
    // declares runInContext. We cannot enumerate a runtime object's properties at
    // compile time, so collect the property names the module actually reads off the
    // namespace binding — precise, and derived from the same source.
    re = /\bimport\s*\*\s*as\s+([A-Za-z0-9_$]+)\s*from\s*"((?:[^"\\]|\\.)*)"/g;
    while ((m = re.exec(src))) {
      if (mods.has(m[2]) || !isPlausibleSpecifier(m[2])) continue;
      var nsSet = want(m[2]);
      var nsRe = new RegExp('\\b' + m[1] + '\\.([A-Za-z_$][A-Za-z0-9_$]*)', 'g');
      var nm;
      while ((nm = nsRe.exec(src))) nsSet[nm[1]] = 1;
    }

    for (i = 0; i < IMPORT_RES.length; i++) {
      re = new RegExp(IMPORT_RES[i].source, 'g');
      while ((m = re.exec(src))) {
        spec = m[1];
        if (!mods.has(spec) && isPlausibleSpecifier(spec)) want(spec);
      }
    }
  }
  return ext;
}

// One module per external specifier, re-exporting what the bundle asks for. Runtime
// lookup goes through a single global the bootstrap installs, so there is exactly one
// seam between generated code and the shim.
function shimSource(spec, names) {
  // WALLS MUST FIRE ON USE, NOT ON IMPORT. The shim marks unimplemented APIs with a
  // throwing getter (`vm.SyntheticModule not implemented`) so a target fails loudly at
  // the moment it needs something we do not have. A naive `export const X = __m["X"]`
  // READS every name while the shim module is evaluating, which trips every wall on the
  // specifier whether the bundle touches it or not — measured: a 2.1.245 build died on
  // vm.SyntheticModule that it never actually uses.
  //
  // So each read is guarded, and a wall is re-thrown FROM THE BINDING: the error is
  // preserved and raised when the bundle calls or constructs it, which is what the wall
  // was for. A non-callable use gets "undefined is not ..." instead, which is less
  // pointed but still a failure rather than silence.
  // THE READS BELOW ARE PROBES, and the shim is told so. Each asks a module for a name
  // the bundle imports; where the host does not implement it the read throws, and we
  // substitute a function that rethrows on CALL — the failure belongs at use, not at
  // import. But the read still reaches node-shim's wall traps, which otherwise cannot
  // tell "clode is enumerating bindings" from "the bundle needs this now". Without this
  // flag, a session that never opened a plugin sandbox reported vm.SourceTextModule as a
  // wall it exercised, and the oracle failed a target that had just completed a full
  // agentic turn.
  //
  // Restored rather than cleared, and NOT wrapped in try/finally: a block would put these
  // `let` declarations out of module scope and break the exports below. No finally is
  // needed because every read already has its own catch, so nothing can throw past them.
  var src = 'const __m = globalThis.__quaudeRequire(' + JSON.stringify(spec) + ');\n'
    + 'const __wasProbing = globalThis.__quaudeShimProbe;\n'
    + 'globalThis.__quaudeShimProbe = true;\n', i, n, out = [];
  for (i = 0; i < names.length; i++) {
    n = names[i];
    // Only bindable identifiers can be named exports; anything else stays reachable
    // through the default export rather than being silently dropped.
    if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(n)) continue;
    if (n === 'default') continue;
    src += 'let ' + n + ';\n'
      + 'try { ' + n + ' = __m[' + JSON.stringify(n) + ']; }\n'
      + 'catch (__e) { const __w = __e; ' + n + ' = function () { throw __w; }; }\n';
    out.push(n);
  }
  src += 'globalThis.__quaudeShimProbe = __wasProbing;\n';
  if (out.length) src += 'export { ' + out.join(', ') + ' };\n';
  return src + 'export default __m;\n';
}

// Topological order, dependencies first. Throws on a cycle — the compile step cannot
// recover from one, and failing here names the two modules involved.
function planOrder(mods) {
  var order = [], state = {}, name;
  var inGraph = function (s) { return mods.has(s); };
  for (name of mods.keys()) state['#' + name] = 0;
  for (name of mods.keys()) {
    if (state['#' + name] !== 0) continue;
    var stack = [[name, depsOf(mods.get(name), inGraph), 0]];
    state['#' + name] = 1;
    while (stack.length) {
      var fr = stack[stack.length - 1];
      if (fr[2] >= fr[1].length) { state['#' + fr[0]] = 2; order.push(fr[0]); stack.pop(); continue; }
      var nx = fr[1][fr[2]++];
      var st = state['#' + nx];
      if (st === 1) {
        throw new Error('bun-graph-plan: import cycle ' + fr[0] + ' -> ' + nx
          + '. compile() resolves imports as it compiles, so a cycle has no valid order.');
      }
      if (st === 0) { state['#' + nx] = 1; stack.push([nx, depsOf(mods.get(nx), inGraph), 0]); }
    }
  }
  return order;
}

// mods: Map<name, source> from bun-graph. entry: the graph's entry name.
// Returns { entry, order, sources } where `order` lists every unit to compile,
// shims first, and `sources` maps name -> source for all of them.
function planGraph(mods, entry) {
  if (!mods || typeof mods.get !== 'function') throw new Error('bun-graph-plan: mods must be a Map');
  if (!mods.has(entry)) throw new Error('bun-graph-plan: entry ' + entry + ' is not in the graph');

  var ext = externalsOf(mods);
  var sources = {}, shimNames = [], spec, name;
  for (spec in ext) {
    if (!Object.prototype.hasOwnProperty.call(ext, spec)) continue;
    sources[spec] = shimSource(spec, Object.keys(ext[spec]));
    shimNames.push(spec);
  }
  var order = planOrder(mods);
  for (name of mods.keys()) sources[name] = mods.get(name);

  return {
    entry: entry,
    // Shims first: they depend on nothing, and every real module may need them.
    order: shimNames.concat(order),
    sources: sources,
    externals: shimNames,
    moduleCount: order.length,
  };
}

// CJS require() targets that are modules of this graph. Upstream 2.1.248+ emits these — 278
// distinct edges in 2.1.250, zero in 2.1.247. indexOf rather than a regex ON PURPOSE: these
// sources reach tens of megabytes and a global regex over them blows the stack (measured).
function requiresOf(src, inGraph) {
  var out = [], seen = {}, t = String(src), quotes = ['"', "'"], qi, q, k, end, spec;
  if (t.indexOf('require(') === -1) return out;
  for (qi = 0; qi < quotes.length; qi++) {
    q = quotes[qi];
    k = 0;
    while ((k = t.indexOf('require(' + q, k)) !== -1) {
      end = t.indexOf(q, k + 9);
      if (end === -1) break;
      spec = t.slice(k + 9, end);
      if (inGraph(spec) && !seen['#' + spec]) { seen['#' + spec] = 1; out.push(spec); }
      k = end + 1;
    }
  }
  return out;
}

// Split every require edge by whether turning it into a STATIC IMPORT would close a cycle.
//
// This distinction is the whole fix. Measured on 2.1.250: 245 of 278 edges are safe, and the
// edge that actually breaks CI is one of them — its target has no static path back, so it is
// not part of a cycle at all, it is simply a module nothing ever evaluates. A safe edge can
// become an ordinary import, which the engine resolves natively with no runtime machinery.
function classifyRequires(mods) {
  var names = [], name, i;
  for (name of mods.keys()) names.push(name);
  var idx = new Map();
  for (i = 0; i < names.length; i++) idx.set(names[i], i);
  var inGraph = function (s) { return idx.has(s); };

  var deps = names.map(function (n) {
    return depsOf(mods.get(n), inGraph).map(function (s) { return idx.get(s); });
  });

  // Does a STATIC-import path run from `from` to `to`? Iterative: ~1800 nodes overflows a
  // recursive walk.
  function reaches(from, to) {
    var seen = new Uint8Array(names.length), stack = [from], v, j;
    while (stack.length) {
      v = stack.pop();
      if (seen[v]) continue;
      seen[v] = 1;
      if (v === to) return true;
      for (j = 0; j < deps[v].length; j++) if (!seen[deps[v][j]]) stack.push(deps[v][j]);
    }
    return false;
  }

  // INCREMENTAL, AND THIS IS THE WHOLE CORRECTNESS ARGUMENT. Testing every edge against the
  // ORIGINAL graph is wrong: two edges can each be individually safe and still COMPOSE into a
  // cycle once both are converted. Measured — that mistake produced a 29-module cycle on
  // 2.1.250, made of 2 converted requires and 2 pre-existing static imports, and planGraph
  // rejected the graph. So each safe edge is COMMITTED into the working graph before the next
  // edge is tested, and a later edge sees the earlier ones.
  //
  // Greedy and order-dependent, so not necessarily the largest possible safe set. It does not
  // need to be: under-converting merely leaves an edge for Task 3 to name, while
  // over-converting breaks the build.
  var safe = [], cyclic = [], targets, t, v;
  for (i = 0; i < names.length; i++) {
    targets = requiresOf(mods.get(names[i]), inGraph);
    targets.sort();
    for (t = 0; t < targets.length; t++) {
      v = idx.get(targets[t]);
      if (reaches(v, i)) {
        cyclic.push([names[i], targets[t]]);
      } else {
        safe.push([names[i], targets[t]]);
        deps[i].push(v);
      }
    }
  }
  return { safe: safe, cyclic: cyclic };
}

if (typeof module === 'object' && module.exports) {
  module.exports = { planGraph, planOrder, externalsOf, shimSource, depsOf, isPlausibleSpecifier, requiresOf, classifyRequires };
}
